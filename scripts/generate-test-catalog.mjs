const COLD_FORMS = new Set(['pen']);

function ean13(body12) {
  const digits = [...body12].map(Number);
  const sum = digits.reduce((total, digit, index) => total + digit * (index % 2 === 0 ? 1 : 3), 0);
  return `${body12}${(10 - (sum % 10)) % 10}`;
}

function pick(list) {
  return list[Math.floor(random() * list.length)];
}

function price([low, high], weight) {
  const raw = low + (high - low) * (0.25 * random() + 0.45 * weight * weight);
  return raw.toFixed(2);
}

function csv(value) {
  const text = String(value);
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

const header = [
  'Item Code',
  'Brand Name',
  'Generic',
  'Strength',
  'Form',
  'Pack',
  'Unit',
  'Price',
  'Trade Price',
  'Company',
  'Rx',
  'Storage',
  'Requires Secured Storage',
  'Barcode',
  'Tax',
];
const rows = [header.join(',')];
const names = new Set();
let serial = 0;

for (const [generic, , rx, formSpecs, brands, popularity, options = {}] of MOLECULES) {
  // Brand owners first, then company generics; popular molecules have more manufacturers.
  const generics = [...COMPANIES]
    .sort(() => random() - 0.5)
    .slice(0, popularity)
    .map((company) => [`${generic.split(' ')[0]} ${company.split(' ')[0]}`, company]);
  const sellers = [...brands, ...generics];
  for (const spec of formSpecs) {
    const [formKey, strengthList] = spec.split(':');
    const form = FORMS[formKey];
    if (!form) throw new Error(`Unknown form ${formKey}`);
    const [label, unitName, packs, range] = form;
    const strengths = strengthList.split(',');
    for (const [sellerIndex, [brand, company]] of sellers.entries()) {
      // Not every company makes every strength; brand owners carry the full range.
      for (const [strengthIndex, strength] of strengths.entries()) {
        if (sellerIndex >= brands.length && strengths.length > 1 && random() < 0.35) continue;
        const name = `${brand} ${strength} ${label}`;
        if (names.has(name)) continue;
        names.add(name);
        serial += 1;
        const weight = (strengthIndex + 1) / strengths.length;
        const unitPrice = price(
          range,
          sellerIndex < brands.length ? Math.min(1, weight + 0.3) : weight,
        );
        const cost = (Number(unitPrice) * (0.78 + 0.07 * random())).toFixed(2);
        const cold = options.cold || COLD_FORMS.has(formKey);
        rows.push(
          [
            `TC-${String(serial).padStart(5, '0')}`,
            name,
            generic,
            strength,
            label.toLowerCase(),
            pick(packs),
            unitName,
            unitPrice,
            cost,
            company,
            rx ? 'yes' : 'no',
            cold ? 'COLD' : 'AMBIENT',
            options.secured ? 'yes' : 'no',
            ean13(`896${String(700_000_000 + serial * 7).slice(0, 9)}`),
            '0',
          ]
            .map(csv)
            .join(','),
        );
      }
    }
  }
}

writeFileSync(output, `${rows.join('\n')}\n`);
process.stdout.write(
  `Wrote ${String(serial)} medicines from ${String(MOLECULES.length)} molecules to ${output}\n`,
);
